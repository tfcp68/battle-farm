import type { TargetKind } from './effects';
import type { Rarity } from './rarity';

/**
 * Action Cards (`docs/rules.md` → Action Cards, Classes). 29 kinds are shuffled
 * into the deck (99 cards); 6 more are Class Cards, granted by a Class and never
 * part of the deck.
 *
 * `Card Value` on an Action Card is the number of Fertilizers the player
 * discards to play it — not a score.
 *
 * Which Class grants which Card is recorded once, in `./classes.ts`; here it is
 * only a flag, so the two files cannot disagree.
 */

export interface ActionDefinition {
	kind: 'action';
	id: string;
	name: string;
	/**
	 * `null` for Class Cards — the rulebook grades only the cards that sit in
	 * the Deck, and a Class Card is never bought from the Market.
	 */
	rarity: Rarity | null;
	/** `Card Value`: Fertilizers discarded to play the card. */
	value: number;
	/** Copies in the standard deck; 0 for Class Cards. */
	deckCount: number;
	isClassCard: boolean;
	target: TargetKind;
	/** Rules text — the specification the phase-3 effect must implement. */
	text: string;
}

